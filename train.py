def _checkpoint_paths(cfg):
    return {
        "best": os.path.join(cfg.checkpoint_dir, "best.pt"),
        "latest": os.path.join(cfg.checkpoint_dir, "latest.pt"),
        "meta": os.path.join(cfg.checkpoint_dir, "checkpoint_meta.json"),
    }


def _timestamp():
    return time.strftime("%Y%m%d-%H%M%S")


def _save_best_atomic(cfg, net):
    """Atomically publish arena-accepted weights for serving/evaluation."""
    path = _checkpoint_paths(cfg)["best"]
    tmp = path + ".tmp"
    torch.save(net.state_dict(), tmp)
    os.replace(tmp, path)
    return path


def _save_meta(cfg, *, run_id, iteration, generation, optimizer_steps,
               replay_size, reason):
    """Atomically write checkpoint_meta.json next to latest.pt."""
    paths = _checkpoint_paths(cfg)
    meta = {
        "schema_version": CHECKPOINT_SCHEMA_VERSION,
        "run_id": run_id,
        "iteration": int(iteration),
        "generation": int(generation),
        "optimizer_steps": int(optimizer_steps),
        "replay_size": int(replay_size),
        "reason": reason,
        "saved_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "config": _config_snapshot(cfg),
    }
    tmp = paths["meta"] + ".tmp"
    with open(tmp, "w") as f:
        json.dump(meta, f, indent=2, sort_keys=True)
    os.replace(tmp, paths["meta"])
    return paths["meta"]


def _mark_checkpoint_reason(cfg, reason):
    """Update only the sidecar reason for an already-durable checkpoint."""
    path = _checkpoint_paths(cfg)["meta"]
    if not os.path.exists(path):
        return None
    with open(path) as f:
        meta = json.load(f)
    meta["reason"] = reason
    meta["saved_at"] = datetime.now(timezone.utc).isoformat(timespec="seconds")
    tmp = path + ".tmp"
    with open(tmp, "w") as f:
        json.dump(meta, f, indent=2, sort_keys=True)
    os.replace(tmp, path)
    return path


def _save_latest(cfg, *, run_id, iteration, generation, optimizer_steps,
                 net, best_net, optimizer, buffer, reason):
    """Persist a full resumable v2 snapshot to `latest.pt` (atomic) plus
    checkpoint_meta.json (atomic)."""
    paths = _checkpoint_paths(cfg)
    payload = {
        "schema_version": CHECKPOINT_SCHEMA_VERSION,
        "run_id": run_id,
        "iteration": int(iteration),
        "generation": int(generation),
        "optimizer_steps": int(optimizer_steps),
        "candidate": net.state_dict(),
        "best": best_net.state_dict(),
        "optimizer": optimizer.state_dict(),
        "torch_rng": torch.get_rng_state(),
        "cuda_rng": torch.cuda.get_rng_state_all() if torch.cuda.is_available() else None,
        "random_rng": random.getstate(),
        "numpy_rng": np.random.get_state(),
        "replay": buffer.state_dict(),
        "config": _config_snapshot(cfg),
    }
    tmp = paths["latest"] + ".tmp"
    torch.save(payload, tmp)
    os.replace(tmp, paths["latest"])
    _save_meta(cfg, run_id=run_id, iteration=iteration, generation=generation,
               optimizer_steps=optimizer_steps, replay_size=len(buffer),
               reason=reason)
    return paths["latest"]


def _load_latest_v2(cfg):
    """Return the latest resumable v2 snapshot, or None if it doesn't exist.

    Raises IncompatibleCheckpointError for legacy/unknown schema — v1
    checkpoints are never auto-loaded.
    """
    path = _checkpoint_paths(cfg)["latest"]
    if not os.path.exists(path):
        return None
    # weights_only=False: the snapshot is self-created and trusted, and it
    # carries non-tensor state (numpy/RNG) that weights_only=True rejects.
    payload = torch.load(path, map_location=getattr(cfg, "device", "cpu"),
                         weights_only=False)
    version = payload.get("schema_version")
    if version != CHECKPOINT_SCHEMA_VERSION:
        raise IncompatibleCheckpointError(
            f"checkpoint {path} has schema_version={version!r}; expected "
            f"{CHECKPOINT_SCHEMA_VERSION}. This looks like a v1 checkpoint — "
            "v1 snapshots are not auto-loadable. Start fresh (or convert) and "
            "resume only from a v2 latest.pt."
        )
    return payload


def _restore_rng(state):
    """Restore torch/cuda/random/numpy RNG states from a v2 snapshot."""
    rng = state["torch_rng"]
    torch.set_rng_state(rng.cpu() if rng.is_cuda else rng)
    if state.get("cuda_rng") and torch.cuda.is_available():
        cuda_rng = state["cuda_rng"]
        if isinstance(cuda_rng, (list, tuple)) and all(
            hasattr(r, "cpu") for r in cuda_rng
        ):
            torch.cuda.set_rng_state_all(
                [r.cpu() if r.is_cuda else r for r in cuda_rng]
            )
    random.setstate(state["random_rng"])
    np.random.set_state(state["numpy_rng"])


def _archive_best(cfg):
    """Move an existing best.pt out of the way before it's overwritten, so a
    fresh (non-resume) start can never silently destroy the incumbent best net."""
    best_path = _checkpoint_paths(cfg)["best"]
    if os.path.exists(best_path):
        archived = os.path.join(cfg.checkpoint_dir, f"best-{_timestamp()}.pt")
        os.replace(best_path, archived)
        print(f"Archived previous best -> {os.path.basename(archived)}", flush=True)


def _archive_latest(cfg):
    """Move an existing latest.pt out of the way on a fresh (non-resume) start
    so a legacy/foreign snapshot is preserved and never silently loaded."""
    latest_path = _checkpoint_paths(cfg)["latest"]
    if os.path.exists(latest_path):
        archived = os.path.join(cfg.checkpoint_dir, f"latest-{_timestamp()}.pt")
        os.replace(latest_path, archived)
        print(f"Archived previous latest -> {os.path.basename(archived)}", flush=True)


def _snapshot_checkpoint(cfg, iteration):
    """Hardlink the just-written latest.pt to a versioned, never-overwritten
    filename so checkpoints are countable and recoverable after a reset."""
    latest_path = _checkpoint_paths(cfg)["latest"]
    if not os.path.exists(latest_path):
        return None
    versioned = os.path.join(
        cfg.checkpoint_dir, f"ckpt-iter{iteration:04d}-{_timestamp()}.pt"
    )
    try:
        os.link(latest_path, versioned)
    except OSError:
        shutil.copy2(latest_path, versioned)
    return versioned


