def _config_snapshot(cfg):
    """JSON-safe subset of the config (class attrs + instance overrides)."""
    snap = {}
    for k in dir(cfg):
        if k.startswith("_"):
            continue
        try:
            v = getattr(cfg, k)
        except Exception:  # noqa: BLE001
            continue
        if isinstance(v, (str, int, float, bool)) or v is None:
            snap[k] = v
    return snap


def _make_run_id(cfg):
    rid = getattr(cfg, "run_id", None)
    if rid:
        return str(rid)
    return uuid.uuid4().hex[:12]


def _seed_all(seed):
    torch.manual_seed(seed)
    random.seed(seed)
    np.random.seed(seed)


