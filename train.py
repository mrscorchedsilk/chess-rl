def run_parallel(cfg=None, resume=False, num_workers=None, on_iteration=None):
    """Self-play / train / arena loop with parallel self-play worker processes.

    CPU-heavy MCTS work runs in `num_workers` processes (one game each, in
    parallel); a shared GPU inference server (a thread here) coalesces their
    leaf evaluations into fat forward passes.  The trainer process owns the
    training net, the arena incumbent (self-play teacher), and the served
    `search_net` copy.  Worker results are consumed as envelopes with
    timeout + liveness checks (see _collect_games).
    """
    import multiprocessing as mp

    if cfg is None:
        cfg = Config()
    if num_workers is None or num_workers < 1:
        num_workers = max(1, getattr(cfg, "selfplay_workers", 8))

    _seed_all(cfg.seed)
    os.makedirs(cfg.checkpoint_dir, exist_ok=True)
    device = getattr(cfg, "device", "cpu")

    # ---- model / optimizer / resume (same semantics as serial run) ----
    net = ChessNet(cfg).to(device)
    best_net = ChessNet(cfg).to(device)
    best_net.load_state_dict(net.state_dict())
    search_net = ChessNet(cfg).to(device)
    search_net.load_state_dict(net.state_dict())
    search_net.eval()
    optimizer = _new_optimizer(cfg, net)
    buffer = ReplayBuffer(
        cfg.replay_buffer_size, cfg.policy_size,
        getattr(cfg, "num_input_planes", 104),
        getattr(cfg, "board_size", 8),
    )

    start_iteration = 1
    generation = 0
    optimizer_steps = 0
    run_id = _make_run_id(cfg)

    if resume:
        state = _load_latest_v2(cfg)  # raises IncompatibleCheckpointError for v1
        if state is not None:
            net.load_state_dict(state["candidate"])
            best_net.load_state_dict(state["best"])
            optimizer.load_state_dict(state["optimizer"])
            _restore_rng(state)
            buffer.load_state_dict(state["replay"])
            run_id = state["run_id"]
            generation = int(state["generation"])
            optimizer_steps = int(state["optimizer_steps"])
            start_iteration = int(state["iteration"]) + 1
            # Self-play always starts from the accepted teacher, never the
            # in-progress candidate restored from the checkpoint.
            search_net.load_state_dict(best_net.state_dict())
            print(
                f"Resumed run {run_id} (next iter {start_iteration}, "
                f"generation {generation}, steps {optimizer_steps})",
                flush=True,
            )

    best_path = _checkpoint_paths(cfg)["best"]
    if not resume:
        _archive_best(cfg)
        _archive_latest(cfg)
    _save_best_atomic(cfg, best_net)

    # ---- spawn worker processes + inference server ----
    ctx = mp.get_context("spawn")
    channels = []
    procs = []
    result_queue = ctx.Queue(maxsize=max(8, num_workers * 2))
    stop_event = ctx.Event()
    teacher_generation = ctx.Value("i", generation)
    for i in range(num_workers):
        req_q = ctx.Queue(maxsize=8)
        resp_q = ctx.Queue(maxsize=8)
        channels.append((req_q, resp_q))
        p = ctx.Process(
            target=worker_loop,
            args=(cfg, req_q, resp_q, result_queue, cfg.seed + 1000 + i,
                  stop_event, i, teacher_generation),
            daemon=True,
        )
        procs.append(p)

    server = InferenceServer(
        search_net, device, channels,
        max_batch=getattr(cfg, "inference_max_batch", 4096),
        min_batch=getattr(cfg, "inference_min_batch", 256),
    )
    server.start()
    for p in procs:
        p.start()
    print(
        f"[parallel] {num_workers} self-play workers + inference server",
        flush=True,
    )

    games_played = (start_iteration - 1) * cfg.games_per_iteration
    num_iterations = int(getattr(cfg, "num_iterations", 1))
    iteration = start_iteration - 1
    completed_iteration = start_iteration - 1
    interrupted = False

    try:
        for iteration in range(start_iteration, num_iterations + 1):
            # ---- 1. self-play: collect games from workers (teacher = best) ----
            server.update_weights(best_net.state_dict())
            # Publish the generation only after the corresponding weights are
            # live. Games already in progress retain their old tag and are
            # discarded by _collect_games after an arena promotion.
            teacher_generation.value = generation
            games = _collect_games(
                cfg, result_queue, procs, cfg.games_per_iteration, stop_event,
                expected_generation=generation, server=server,
            )
            buffer.extend(games)
            games_played += cfg.games_per_iteration

            # ---- 2. real bounded shuffled epochs ----
            train_out = _epoch_train(cfg, net, optimizer, buffer, device)
            optimizer_steps += train_out["steps"]

            # ---- 3. arena gate: candidate vs incumbent best ----
            if iteration % int(getattr(cfg, "arena_every", 10)) == 0:
                outcome = _arena_gate(cfg, net, best_net)
                if outcome["accepted"]:
                    generation += 1
                    best_net.load_state_dict(net.state_dict())
                    best_net.eval()
                    _save_best_atomic(cfg, best_net)
                else:
                    net.load_state_dict(best_net.state_dict())
                    optimizer = _new_optimizer(cfg, net)
                    optimizer_steps = 0
                _log_arena_event(
                    cfg, run_id=run_id, iteration=iteration,
                    generation=generation, wins=outcome["a"],
                    draws=outcome["draws"], losses=outcome["b"],
                    score=outcome["score"], accepted=outcome["accepted"],
                )

            # ---- 4. durable checkpoint after EVERY completed iteration ----
            _save_latest(cfg, run_id=run_id, iteration=iteration,
                         generation=generation,
                         optimizer_steps=optimizer_steps, net=net,
                         best_net=best_net, optimizer=optimizer,
                         buffer=buffer, reason="iteration")
            completed_iteration = iteration
            if iteration % int(getattr(cfg, "checkpoint_every_iterations", 1)) == 0:
                _snapshot_checkpoint(cfg, iteration)

            _log_metrics(cfg, run_id=run_id, iteration=iteration,
                         generation=generation,
                         policy_loss=train_out["policy_loss"],
                         value_loss=train_out["value_loss"],
                         entropy=train_out["entropy"],
                         optimizer_steps=optimizer_steps,
                         replay_size=len(buffer), games=games_played)
            print(
                f"iter {iteration:4d}  gen {generation}  steps {optimizer_steps}"
                f"  buffer {len(buffer)}",
                flush=True,
            )
            if on_iteration is not None:
                on_iteration(iteration)
    except BaseException:
        interrupted = True
        raise
    finally:
        # Shutdown: signal workers, give them a beat to finish the current
        # game, then hard-stop anything left and stop the server.
        stop_event.set()
        for p in procs:
            p.join(timeout=2.0)
        for p in procs:
            if p.is_alive():
                p.terminate()
        for p in procs:
            p.join(timeout=2.0)
        server.stop()
        # Never persist a partially completed parallel iteration. Completed
        # iterations were checkpointed before metrics/callbacks above.
        if interrupted:
            if completed_iteration >= start_iteration:
                _mark_checkpoint_reason(cfg, "interrupt")
            reason = "interrupt"
        elif completed_iteration >= start_iteration:
            _save_latest(cfg, run_id=run_id, iteration=completed_iteration,
                         generation=generation,
                         optimizer_steps=optimizer_steps, net=net,
                         best_net=best_net, optimizer=optimizer,
                         buffer=buffer, reason="final")
            reason = "final"
        else:
            reason = "interrupt" if interrupted else "final"
        print(
            f"{'Training interrupted' if interrupted else 'Training complete.'} "
            f"(saved iteration {completed_iteration}, reason={reason})",
            flush=True,
        )
    _save_best_atomic(cfg, best_net)
    if not interrupted:
        print("Training complete.", flush=True)


