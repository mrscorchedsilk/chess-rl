def run(cfg=None, resume=False, on_iteration=None, warm_start_checkpoint=None):
    """The full self-play / train / arena loop.

    `on_iteration(iteration)` is called after each completed iteration (and its
    checkpoint); raising from it simulates a graceful interruption, which is
    still checkpointed in `finally`.

    `warm_start_checkpoint` starts a NEW training lineage from the accepted-best
    weights of a compatible schema-v3 checkpoint (empty replay, fresh optimizer,
    new run_id) — mutually exclusive with `resume`.
    """
    if cfg is None:
        cfg = Config()

    _seed_all(cfg.seed)
    os.makedirs(cfg.checkpoint_dir, exist_ok=True)
    device = getattr(cfg, "device", "cpu")

    net = ChessNet(cfg).to(device)
    best_net = ChessNet(cfg).to(device)
    best_net.load_state_dict(net.state_dict())
    optimizer = _new_optimizer(cfg, net)
    scaler = _new_scaler(cfg, device)
    buffer = ReplayBuffer(
        cfg.replay_buffer_size, cfg.policy_size,
        getattr(cfg, "num_input_planes", 104),
        getattr(cfg, "board_size", 8),
    )

    start_iteration = 1
    generation = 0
    optimizer_steps = 0
    run_id = _make_run_id(cfg)
    provenance = None

    if warm_start_checkpoint is not None:
        if resume:
            raise ValueError(
                "--resume and --warm-start-checkpoint are mutually exclusive"
            )
        wm = _load_warm_start(cfg, warm_start_checkpoint)
        net.load_state_dict(wm["best"])
        best_net.load_state_dict(wm["best"])
        # optimizer/scaler/buffer stay fresh (empty) from construction above;
        # generation/steps/iteration reset for the new corrected lineage.
        generation = 0
        optimizer_steps = 0
        start_iteration = 1
        run_id = _make_run_id(cfg)  # new lineage -> new run id
        provenance = {
            "parent_run_id": wm["parent_run_id"],
            "parent_iteration": wm["parent_iteration"],
            "parent_generation": wm["parent_generation"],
            "warm_started_from": wm["warm_started_from"],
        }
        print(
            f"Warm-started new lineage {run_id} from {wm['warm_started_from']} "
            f"(parent run {wm['parent_run_id']}, "
            f"iter {wm['parent_iteration']}, gen {wm['parent_generation']})",
            flush=True,
        )
    elif resume:
        state = _load_latest_v2(cfg)  # raises IncompatibleCheckpointError for v1
        if state is not None:
            net.load_state_dict(state["candidate"])
            best_net.load_state_dict(state["best"])
            optimizer.load_state_dict(state["optimizer"])
            if state.get("scaler"):
                scaler.load_state_dict(state["scaler"])
            _restore_rng(state)
            buffer.load_state_dict(state["replay"])
            run_id = state["run_id"]
            generation = int(state["generation"])
            optimizer_steps = int(state["optimizer_steps"])
            start_iteration = int(state["iteration"]) + 1
            print(
                f"Resumed run {run_id} (next iter {start_iteration}, "
                f"generation {generation}, steps {optimizer_steps})",
                flush=True,
            )

    best_path = _checkpoint_paths(cfg)["best"]
    if not resume:
        _archive_best(cfg)
        _archive_latest(cfg)   # never auto-load a stale/legacy latest.pt
    _save_best_atomic(cfg, best_net)

    games_played = (start_iteration - 1) * cfg.games_per_iteration
    num_iterations = int(getattr(cfg, "num_iterations", 1))
    iteration = start_iteration - 1
    completed_iteration = start_iteration - 1
    interrupted = False
    round_seed = None

    try:
        for iteration in range(start_iteration, num_iterations + 1):
            # ---- 1. self-play with the ACCEPTED best as teacher ----
            net.eval()
            best_net.eval()
            buf_before = len(buffer)
            with telemetry.PhaseTimer("selfplay") as _sp_timer:
                for _ in range(cfg.games_per_iteration):
                    buffer.extend(play_game(best_net, cfg))
                    games_played += 1
            try:
                telemetry.safe_emit(cfg, {
                    "type": "phase",
                    "phase": "selfplay",
                    "run_id": run_id,
                    "iteration": iteration,
                    "generation": generation,
                    "duration_s": _sp_timer.duration_s,
                    "games": cfg.games_per_iteration,
                    "examples": len(buffer) - buf_before,
                })
            except Exception:  # noqa: BLE001 - telemetry must never kill training
                pass

            # ---- 2. real bounded shuffled epochs ----
            train_out = _epoch_train(cfg, net, optimizer, buffer, device, scaler,
                                     run_id=run_id, iteration=iteration,
                                     generation=generation,
                                     optimizer_steps_total=optimizer_steps)
            optimizer_steps += train_out["steps"]

            # ---- 3. arena gate: candidate vs incumbent best ----
            if iteration % int(getattr(cfg, "arena_every", 10)) == 0:
                outcome = _arena_gate(cfg, net, best_net, run_id=run_id,
                                      iteration=iteration, generation=generation)
                if outcome["accepted"]:
                    generation += 1
                    best_net.load_state_dict(net.state_dict())
                    best_net.eval()
                    _save_best_atomic(cfg, best_net)
                    _save_milestone(cfg, best_net, run_id=run_id,
                                    iteration=iteration, generation=generation,
                                    outcome=outcome)
                else:
                    # Rejected challenger: revert to best and reset the
                    # optimizer so it can never silently become the teacher.
                    net.load_state_dict(best_net.state_dict())
                    optimizer = _new_optimizer(cfg, net)
                    optimizer_steps = 0
                _log_arena_event(
                    cfg, run_id=run_id, iteration=iteration,
                    generation=generation, wins=outcome["a"],
                    draws=outcome["draws"], losses=outcome["b"],
                    score=outcome["score"], accepted=outcome["accepted"],
                    opening_seed=outcome.get("opening_seed"),
                    opening_pairs=outcome.get("opening_pairs"),
                    opening_suite_hash=outcome.get("opening_suite_hash"),
                )

            # ---- 4. durable checkpoint after EVERY completed iteration ----
            _save_latest(cfg, run_id=run_id, iteration=iteration,
                         generation=generation,
                         optimizer_steps=optimizer_steps, net=net,
                         best_net=best_net, optimizer=optimizer,
                         buffer=buffer, reason="iteration",
                         scaler=scaler, device=device, provenance=provenance)
            completed_iteration = iteration
            if iteration % int(getattr(cfg, "checkpoint_every_iterations", 1)) == 0:
                _snapshot_checkpoint(cfg, iteration, run_id=run_id,
                                     generation=generation)

            _log_metrics(cfg, run_id=run_id, iteration=iteration,
                         generation=generation,
                         policy_loss=train_out["policy_loss"],
                         value_loss=train_out["value_loss"],
                         entropy=train_out["entropy"],
                         optimizer_steps=optimizer_steps,
                         replay_size=len(buffer), games=games_played,
                         round_seed=round_seed)
            print(
                f"iter {iteration:4d}  gen {generation}  steps {optimizer_steps}"
                f"  buffer {len(buffer)}  "
                f"p {train_out['policy_loss']:.4f} v {train_out['value_loss']:.4f}",
                flush=True,
            )
            if on_iteration is not None:
                on_iteration(iteration)
    except BaseException:
        interrupted = True
        raise
    finally:
        # A partial iteration is never checkpointed. Each completed iteration
        # was already saved atomically above; an interrupt only annotates that
        # last good checkpoint. Normal completion writes a final reason marker.
        if interrupted:
            if completed_iteration >= start_iteration:
                _mark_checkpoint_reason(cfg, "interrupt")
            reason = "interrupt"
        elif completed_iteration >= start_iteration:
            _save_latest(cfg, run_id=run_id, iteration=completed_iteration,
                         generation=generation,
                         optimizer_steps=optimizer_steps, net=net,
                         best_net=best_net, optimizer=optimizer,
                         buffer=buffer, reason="final",
                         scaler=scaler, device=device, provenance=provenance)
            reason = "final"
        else:
            reason = "interrupt" if interrupted else "final"
        print(
            f"{'Training interrupted' if interrupted else 'Training complete.'} "
            f"(saved iteration {completed_iteration}, reason={reason})",
            flush=True,
        )
    _save_best_atomic(cfg, best_net)
    if not interrupted:
        print("Training complete.", flush=True)


