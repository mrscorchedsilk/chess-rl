def _new_optimizer(cfg, net):
    return Adam(net.parameters(), lr=cfg.learning_rate,
                weight_decay=getattr(cfg, "weight_decay", 1e-4))


def _epoch_train(cfg, net, optimizer, buffer, device):
    """Run `training_epochs` REAL epochs over a bounded, per-epoch-shuffled
    sample from the replay buffer.  Each minibatch is one optimizer step.

    Returns dict(policy_loss, value_loss, entropy, steps, batches) — losses are
    averaged over all minibatches, steps counts actual optimizer.step() calls.
    """
    n = len(buffer)
    epochs = int(getattr(cfg, "training_epochs",
                         getattr(cfg, "epochs_per_iteration", 3)))
    if n == 0 or epochs <= 0:
        return {"policy_loss": 0.0, "value_loss": 0.0, "entropy": 0.0,
                "steps": 0, "batches": 0}
    sample_size = min(
        n,
        int(getattr(cfg, "train_epoch_size", 0)
            or (cfg.train_batch_size * epochs)),
    )
    if sample_size <= 0:
        return {"policy_loss": 0.0, "value_loss": 0.0, "entropy": 0.0,
                "steps": 0, "batches": 0}

    net.train()
    sum_policy = sum_value = sum_entropy = 0.0
    steps = batches = 0
    for _ in range(epochs):
        # Uniform sample from the entire replay, freshly shuffled each epoch.
        # Sampling only permutation(sample_size) would repeatedly train the
        # oldest prefix and starve newly generated positions.
        rows = np.random.choice(n, size=sample_size, replace=False)
        for start in range(0, sample_size, cfg.train_batch_size):
            batch_rows = rows[start:start + cfg.train_batch_size]
            states, pis, zs = buffer.sample_indices(batch_rows, device)
            logits, value = net(states)
            policy_loss = F.cross_entropy(logits, pis)
            value_loss = F.mse_loss(value, zs)
            probs = F.softmax(logits, dim=1)
            entropy = -(probs * (probs + 1e-12).log()).sum(dim=1).mean()
            loss = policy_loss + value_loss
            optimizer.zero_grad()
            loss.backward()
            optimizer.step()
            sum_policy += float(policy_loss.item())
            sum_value += float(value_loss.item())
            sum_entropy += float(entropy.item())
            steps += 1
            batches += 1
    return {
        "policy_loss": sum_policy / batches,
        "value_loss": sum_value / batches,
        "entropy": sum_entropy / batches,
        "steps": steps,
        "batches": batches,
    }


def _arena_gate(cfg, net, best_net):
    """Candidate vs incumbent best.  Standard score = (wins + 0.5*draws)/games.

    Returns dict(a, b, draws, games, score, accepted).
    """
    net.eval()
    best_net.eval()
    result = play_match(net, best_net, cfg, num_games=cfg.arena_games)
    wins = int(result["a"])
    losses = int(result["b"])
    draws = int(result["draws"])
    games = wins + losses + draws
    score = (wins + 0.5 * draws) / games if games else 0.0
    accepted = score >= float(getattr(cfg, "arena_accept_threshold", 0.55))
    return {"a": wins, "b": losses, "draws": draws, "games": games,
            "score": score, "accepted": accepted}


# --------------------------------------------------------------------------- #
#  parallel result envelopes (timeout + liveness)                              #
# --------------------------------------------------------------------------- #

def _unpack_worker_result(item):
    """Normalize a parallel self-play result into ("game", examples) or
    ("error", detail).  Accepts the envelope format
    {"kind": "game"|"error", ...} (examples under "examples"/"payload") and
    the legacy raw-example list, so train.py is forward-compatible with
    parallel.py's result envelopes.
    """
    if isinstance(item, dict):
        kind = item.get("kind")
        if kind == "error":
            detail = (item.get("traceback") or item.get("message")
                      or item.get("error") or "unknown worker error")
            return "error", str(detail)
        if kind == "game":
            payload = item.get("examples", item.get("game",
                                                    item.get("payload", None)))
            if payload is None:
                return "unknown", item
            return "game", list(payload)
        return "unknown", item
    if isinstance(item, (list, tuple)):
        return "game", list(item)
    return "unknown", item


def _collect_games(cfg, result_queue, procs, games_needed, stop_event=None,
                   expected_generation=None, server=None):
    """Collect exactly ``games_needed`` game envelopes and flatten examples.

    Queue silence, worker/server death, protocol mismatch, or an error envelope
    becomes a bounded RuntimeError. When ``expected_generation`` is supplied,
    stale games from a previous accepted teacher are discarded.
    """
    timeout = float(getattr(cfg, "result_timeout_seconds", 60))
    examples = []
    game_count = 0
    while game_count < games_needed:
        if stop_event is not None and stop_event.is_set():
            raise RuntimeError("self-play stopped before enough games were collected")
        if server is not None and not server.is_alive():
            detail = server.get_error() if hasattr(server, "get_error") else None
            raise RuntimeError(f"inference server stopped: {detail or 'unknown error'}")
        try:
            item = result_queue.get(timeout=timeout)
        except queue.Empty:
            dead = [p for p in procs if not p.is_alive()]
            if dead:
                raise RuntimeError(
                    f"{len(dead)} self-play worker(s) died while waiting for games"
                )
            if server is not None and not server.is_alive():
                detail = server.get_error() if hasattr(server, "get_error") else None
                raise RuntimeError(f"inference server stopped: {detail or 'unknown error'}")
            raise RuntimeError(
                f"timed out after {timeout}s without a completed self-play game"
            )

        kind, payload = _unpack_worker_result(item)
        if kind == "error":
            raise RuntimeError(f"self-play worker error: {payload}")
        if kind != "game":
            raise RuntimeError(f"unknown self-play result envelope: {item!r}")
        if expected_generation is not None and isinstance(item, dict):
            item_generation = item.get("generation")
            if item_generation is not None and int(item_generation) != int(expected_generation):
                continue
        examples.extend(payload)
        game_count += 1
    return examples


